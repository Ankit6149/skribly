import { readFile, writeFile } from 'node:fs/promises';

function lines(values) {
  return values.join('\n');
}

async function edit(path, transform) {
  const before = await readFile(path, 'utf8');
  const after = transform(before);
  if (after === before) {
    throw new Error(`${path}: transformation made no change`);
  }
  await writeFile(path, after, 'utf8');
}

function replaceExact(source, before, after, label) {
  const occurrences = source.split(before).length - 1;
  if (occurrences !== 1) {
    throw new Error(`${label}: expected one exact match, found ${occurrences}`);
  }
  return source.replace(before, after);
}

function replaceRegex(source, pattern, after, label) {
  const matches = [...source.matchAll(new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`))];
  if (matches.length !== 1) {
    throw new Error(`${label}: expected one regex match, found ${matches.length}`);
  }
  return source.replace(pattern, after);
}

